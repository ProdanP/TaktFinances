        ThemeContrast.High -> lightHighContrast
    }
    true -> when (contrast) {
        ThemeContrast.Standard -> darkStandard
        ThemeContrast.Medium -> darkMediumContrast
        ThemeContrast.High -> darkHighContrast
    }
}
